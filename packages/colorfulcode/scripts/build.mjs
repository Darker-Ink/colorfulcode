// Builds the WebAssembly module and assembles `dist/`.
//
// The wasm binary is embedded as base64 so the package works everywhere
// (Node, Deno, Bun, browsers, every bundler) without any configuration, and
// so it can be instantiated synchronously.

import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const repo = join(root, "..", "..");
const dist = join(root, "dist");
const wasmPath = join(repo, "target", "wasm32-unknown-unknown", "release", "colorfulcode_wasm.wasm");

const run = (cmd, args) => execFileSync(cmd, args, { cwd: repo, stdio: "inherit" });

run("cargo", ["build", "--release", "--target", "wasm32-unknown-unknown", "-p", "colorfulcode-wasm"]);

let wasm = readFileSync(wasmPath);
try {
  // Optional: shrink and speed up the module when binaryen is installed.
  const optimized = join(repo, "target", "colorfulcode.opt.wasm");
  execFileSync("wasm-opt", ["-O3", "--enable-bulk-memory", "--enable-sign-ext", "--enable-nontrapping-float-to-int", "--enable-mutable-globals", wasmPath, "-o", optimized], { stdio: "ignore" });
  wasm = readFileSync(optimized);
} catch {
  console.warn("wasm-opt not found, using the unoptimized module");
}

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist);
writeFileSync(
  join(dist, "wasm.js"),
  `// Generated by scripts/build.mjs. Do not edit.\nexport default ${JSON.stringify(wasm.toString("base64"))};\n`,
);
for (const file of readdirSync(join(root, "src"))) {
  copyFileSync(join(root, "src", file), join(dist, file));
}
console.log(`dist ready: wasm ${(wasm.length / 1024).toFixed(0)} KiB`);

// Prebuilt theme stylesheets for the class based output.
const { listThemes, themeCss } = await import(join(dist, "index.js"));
mkdirSync(join(dist, "themes"));
for (const { name } of listThemes()) {
  writeFileSync(join(dist, "themes", `${name}.css`), themeCss(name));
}
