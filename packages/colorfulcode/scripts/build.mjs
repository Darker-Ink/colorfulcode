// Builds the WebAssembly module and assembles `dist/`.
//
// The wasm binary is embedded as base64 so the package works everywhere
// (Node, Deno, Bun, browsers, every bundler) without any configuration, and
// so it can be instantiated synchronously.

import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const repo = join(root, "..", "..");
const dist = join(root, "dist");
const wasmPath = join(repo, "target", "wasm32-unknown-unknown", "release", "colorfulcode_wasm.wasm");

const run = (cmd, args) => execFileSync(cmd, args, { cwd: repo, stdio: "inherit" });

// Two builds: every language, and a smaller one with the most used languages.
function buildWasm(features) {
  run("cargo", ["build", "--release", "--target", "wasm32-unknown-unknown", "-p", "colorfulcode-wasm", ...features]);
  try {
    // Optional: shrink and speed up the module when binaryen is installed.
    const optimized = join(repo, "target", "colorfulcode.opt.wasm");
    execFileSync("wasm-opt", ["-O3", "--enable-bulk-memory", "--enable-sign-ext", "--enable-nontrapping-float-to-int", "--enable-mutable-globals", wasmPath, "-o", optimized], { stdio: "ignore" });
    return readFileSync(optimized);
  } catch {
    console.warn("wasm-opt not found, using the unoptimized module");
    return readFileSync(wasmPath);
  }
}

const full = buildWasm([]);
const common = buildWasm(["--no-default-features"]);

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist);
const writeWasm = (file, wasm) =>
  writeFileSync(join(dist, file), `// Generated by scripts/build.mjs. Do not edit.\nexport default ${JSON.stringify(wasm.toString("base64"))};\n`);
writeWasm("wasm.js", full);
writeWasm("wasm-common.js", common);
for (const file of readdirSync(join(root, "src"))) {
  copyFileSync(join(root, "src", file), join(dist, file));
}
// The common entry points are the same code bound to the smaller module.
const copyWith = (from, to, replacements) => {
  let text = readFileSync(join(dist, from), "utf8");
  for (const [a, b] of replacements) text = text.replaceAll(a, b);
  writeFileSync(join(dist, to), text);
};
copyWith("index.js", "common.js", [['from "./wasm.js"', 'from "./wasm-common.js"']]);
copyWith("react.js", "common-react.js", [['"./index.js"', '"./common.js"']]);
writeFileSync(join(dist, "common.d.ts"), 'export * from "./index.js";\n');
writeFileSync(join(dist, "common-react.d.ts"), 'export * from "./react.js";\nexport { default } from "./react.js";\n');

const kib = (b) => `${(b.length / 1024).toFixed(0)} KiB`;
console.log(`dist ready: full wasm ${kib(full)}, common wasm ${kib(common)}`);

// Prebuilt theme stylesheets for the class based output.
const { listThemes, themeCss } = await import(join(dist, "index.js"));
mkdirSync(join(dist, "css"));
for (const { name } of listThemes()) {
  writeFileSync(join(dist, "css", `${name}.css`), themeCss(name));
}
