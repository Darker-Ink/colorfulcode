// Builds the WebAssembly modules and assembles `dist/`.
//
// The default and common entries embed their module as base64 so they work
// everywhere (Node, Deno, Bun, browsers, every bundler) without configuration
// and load synchronously. The web entry loads a separate `colorfulcode.wasm`
// instead, which is smaller to download and compiles while it streams.

import { execFileSync, execSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const repo = join(root, "..", "..");
const dist = join(root, "dist");
const run = (cmd, args, env) => execFileSync(cmd, args, { cwd: repo, stdio: "inherit", env: { ...process.env, ...env } });

// Optional: shrink and speed up the module when binaryen is installed.
function wasmOpt(level, input, output) {
  const args = [level, "--enable-bulk-memory", "--enable-sign-ext", "--enable-nontrapping-float-to-int", "--enable-mutable-globals", input, "-o", output];
  // On Windows wasm-opt is a .cmd shim, which Node only runs through a shell.
  if (process.platform === "win32") {
    execSync(`wasm-opt ${args.map((a) => `"${a}"`).join(" ")}`, { stdio: "ignore" });
  } else {
    execFileSync("wasm-opt", args, { stdio: "ignore" });
  }
}

/**
 * Builds the wasm crate. `size` optimizes for size instead of speed; it gets
 * its own target directory so switching does not rebuild everything.
 */
function buildWasm(features, { size = false } = {}) {
  const targetDir = join(repo, "target", size ? "wasm-size" : "");
  const env = size ? { CARGO_TARGET_DIR: targetDir, CARGO_PROFILE_RELEASE_OPT_LEVEL: "s" } : {};
  run("cargo", ["build", "--release", "--target", "wasm32-unknown-unknown", "-p", "colorfulcode-wasm", ...features], env);
  const wasmPath = join(targetDir, "wasm32-unknown-unknown", "release", "colorfulcode_wasm.wasm");
  try {
    const optimized = join(targetDir, "colorfulcode.opt.wasm");
    wasmOpt(size ? "-Os" : "-O3", wasmPath, optimized);
    return readFileSync(optimized);
  } catch {
    console.warn("wasm-opt not found, using the unoptimized module");
    return readFileSync(wasmPath);
  }
}

// Every language and the most used ones, both fast and embedded as base64 so
// they load synchronously; and the most used ones optimized for size as a
// separate file for `colorfulcode/web`.
const full = buildWasm([]);
const common = buildWasm(["--no-default-features"]);
const web = buildWasm(["--no-default-features"], { size: true });

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist);
const writeWasm = (file, wasm) =>
  writeFileSync(join(dist, file), `// Generated by scripts/build.mjs. Do not edit.\nexport default ${JSON.stringify(wasm.toString("base64"))};\n`);
writeWasm("wasm.js", full);
writeWasm("wasm-common.js", common);
writeFileSync(join(dist, "colorfulcode.wasm"), web);
for (const file of readdirSync(join(root, "src"))) {
  copyFileSync(join(root, "src", file), join(dist, file));
}
// The common entry points are the same code bound to the smaller module.
const copyWith = (from, to, replacements) => {
  let text = readFileSync(join(dist, from), "utf8");
  for (const [a, b] of replacements) text = text.replaceAll(a, b);
  writeFileSync(join(dist, to), text);
};
copyWith("index.js", "common.js", [['from "./wasm.js"', 'from "./wasm-common.js"']]);
copyWith("react.js", "common-react.js", [['"./index.js"', '"./common.js"']]);
copyWith("react.js", "web-react.js", [['"./index.js"', '"./web.js"']]);
for (const entry of ["common", "web"]) {
  writeFileSync(join(dist, `${entry}.d.ts`), 'export * from "./index.js";\n');
  writeFileSync(join(dist, `${entry}-react.d.ts`), 'export * from "./react.js";\nexport { default } from "./react.js";\n');
}

const kib = (b) => `${(b.length / 1024).toFixed(0)} KiB`;
console.log(`dist ready: full wasm ${kib(full)}, common wasm ${kib(common)}, web wasm ${kib(web)}`);

// Prebuilt theme stylesheets for the class based output.
const { listThemes, themeCss } = await import(pathToFileURL(join(dist, "index.js")).href);
mkdirSync(join(dist, "css"));
for (const { name } of listThemes()) {
  writeFileSync(join(dist, "css", `${name}.css`), themeCss(name));
}
